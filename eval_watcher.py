import os
import time
import glob
import torch
from diplomacy_helpers import DiplomacyTransformerEnv, DiplomacyTransformer
from RL import rebuild_dense_mask

DEVICE = torch.device("cuda:0" if torch.cuda.is_available() else "cpu")

def play_eval_game(ckpt_path, game_id, save_dir="./eval_games"):
    os.makedirs(save_dir, exist_ok=True)
    log_path = os.path.join(save_dir, f"sf2_eval_game_{game_id}.txt")
    
    print(f"Loading weights from {ckpt_path} for Game {game_id}...")
    
    env = DiplomacyTransformerEnv(history_length=3)
    
    # Notice input_dim=25 to match your new Phase Encoder
    net = DiplomacyTransformer(
        input_dim=25, 
        num_provinces=env.num_provinces, 
        history_length=3, 
        vocab_size=env.vocab_size
    ).to(DEVICE)
    
    # 1. LOAD SF2 CHECKPOINT
    checkpoint = torch.load(ckpt_path, map_location=DEVICE)
    # SF2 buries the weights inside a dictionary depending on the save state
    state_dict = checkpoint.get("model_state_dict", checkpoint) 
    
    clean_state_dict = {}
    for k, v in state_dict.items():
        # SF2 wraps our model in the ActorCritic class, appending "transformer." to the keys.
        # We must strip that prefix off to load it into the raw network.
        if k.startswith("transformer."):
            clean_state_dict[k.replace("transformer.", "")] = v
        else:
            clean_state_dict[k] = v
            
    net.load_state_dict(clean_state_dict, strict=False)
    net.eval()
    
    # 2. PLAY THE GAME
    obs, infos = env.reset()
    
    with open(log_path, "w") as f:
        f.write(f"SF2 Evaluation Game - Checkpoint {game_id}\n")
        f.write(f"Weights: {os.path.basename(ckpt_path)}\n")
        f.write("========================================\n")
        
        step_count = 0
        while len(env.agents) > 0 and step_count < 150:
            phase_name = env.game.get_current_phase()
            f.write(f"\n--- Phase {phase_name} ---\n")
            
            active_agents = env.agents
            obs_tensor = torch.stack([torch.tensor(obs[a]) for a in active_agents]).to(DEVICE)
            
            sparse_masks_tensor = torch.stack([torch.tensor(infos[a]['action_mask'], dtype=torch.long) for a in active_agents]).to(DEVICE)
            masks_tensor = rebuild_dense_mask(sparse_masks_tensor, env.num_provinces, env.vocab_size, DEVICE)
            
            with torch.no_grad():
                with torch.autocast(device_type='cuda', dtype=torch.bfloat16):
                    state_repr, _ = net.encode_state(obs_tensor)
                    
                batch_size = obs_tensor.size(0)
                current_action = torch.zeros(batch_size, dtype=torch.long, device=DEVICE)
                kv_cache = None
                actions_list = []
                
                for prov_idx in range(env.num_provinces):
                    with torch.autocast(device_type='cuda', dtype=torch.bfloat16):
                        logits, kv_cache = net.decode_step(current_action, prov_idx, state_repr, kv_cache)
                    
                    logits = logits.float()
                    prov_mask = masks_tensor[:, prov_idx, :]
                    logits = logits.masked_fill(~prov_mask, -1e4)
                    
                    current_action = torch.argmax(logits, dim=-1)
                    actions_list.append(current_action)
                    
                actions = torch.stack(actions_list, dim=1)
                
            action_dict = {a: actions[i].cpu().numpy() for i, a in enumerate(active_agents)}
            
            for idx, agent in enumerate(active_agents):
                f.write(f"{agent} Orders\n")
                orders_issued = False
                for prov_idx, order_idx in enumerate(actions[idx]):
                    order_str = env.idx_to_order[order_idx.item()]
                    if order_str != 'NONE':
                        f.write(f"  {order_str}\n")
                        orders_issued = True
                if not orders_issued:
                    f.write("  (No valid orders)\n")
                    
            obs, rewards, terms, truncs, infos = env.step(action_dict)
            step_count += 1
            
        f.write("\n========================================\n")
        f.write("FINAL SUPPLY CENTER COUNTS\n")
        for agent in env.possible_agents:
            scs = env.game.get_centers(agent)
            f.write(f"{agent} {len(scs)}\n")
            
    print(f" -> Game saved to {log_path}")

def watch_checkpoints():
    print("Watcher started. Waiting for SF2 checkpoints to appear in ./sf2_runs/...")
    evaluated_ckpts = set()
    game_id = 1
    
    while True:
        # Search recursively for all .pth files generated by SF2
        pth_files = glob.glob("./sf2_runs/**/*.pth", recursive=True)
        
        if pth_files:
            # Sort them by modification time to find the newest one
            latest_ckpt = max(pth_files, key=os.path.getmtime)
            
            if latest_ckpt not in evaluated_ckpts:
                play_eval_game(latest_ckpt, game_id)
                evaluated_ckpts.add(latest_ckpt)
                game_id += 1
                
        # Sleep for 60 seconds before checking the folder again
        time.sleep(60)

if __name__ == "__main__":
    watch_checkpoints()